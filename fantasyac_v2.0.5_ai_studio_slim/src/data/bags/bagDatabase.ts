export function getBagDefinition(idOrName?: string | null): BagDefinition | undefined {
  if (!idOrName) return undefined;
  const trimmed = idOrName.trim();
  if (BAG_DATABASE[trimmed]) return BAG_DATABASE[trimmed];
  return Object.values(BAG_DATABASE).find((b) => b.name === trimmed);
}
